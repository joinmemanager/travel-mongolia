// Локал экспортоос (export-contentful.js) content model-ийн шинжилгээг гаргана. Contentful руу хүсэлт илгээхгүй.
//   node scripts/payload/analyze-export.js [exportDir] > docs/plan/payload-analysis.generated.md
const fs = require('fs');
const path = require('path');
const { loadExport } = require('./lib/export');

const ex = loadExport(process.argv[2]);
const out = [];
const p = (s = '') => out.push(s);

const statusOf = (sys) =>
  sys.archivedVersion ? 'archived' : !sys.publishedVersion ? 'draft' : sys.version > sys.publishedVersion + 1 ? 'changed' : 'published';

p(`<!-- generated by scripts/payload/analyze-export.js from ${path.basename(ex.dir)} -->`);
p(`Экспорт: ${ex.meta.finishedAt}, хүсэлт ${ex.meta.requests}. Locale: ${ex.locales.map((l) => `${l.code}${l.default ? ' (үндсэн)' : ''}${l.fallbackCode ? ` → ${l.fallbackCode}` : ''}`).join(', ')}.`);
p();

// --- Content type бүрийн тойм
p('| Content type | Нэр | Entry | published / changed / draft | displayField | Талбар |');
p('|---|---|--:|---|---|--:|');
const byType = {};
for (const e of ex.entries) (byType[e.sys.contentType.sys.id] ||= []).push(e);
for (const ct of ex.contentTypes.slice().sort((a, b) => a.sys.id.localeCompare(b.sys.id))) {
  const list = byType[ct.sys.id] || [];
  const st = list.reduce((acc, e) => ((acc[statusOf(e.sys)] = (acc[statusOf(e.sys)] || 0) + 1), acc), {});
  p(`| \`${ct.sys.id}\` | ${ct.name} | ${list.length} | ${st.published || 0} / ${st.changed || 0} / ${st.draft || 0} | ${ct.displayField || ''} | ${ct.fields.length} |`);
}
p();

// --- Талбар бүр
const typeLabel = (f) => {
  if (f.type === 'Link') return `Link→${f.linkType}${f.validations?.find((v) => v.linkContentType) ? `(${f.validations.find((v) => v.linkContentType).linkContentType.join('|')})` : ''}`;
  if (f.type === 'Array') {
    const it = f.items;
    if (it.type === 'Link') return `Array<Link→${it.linkType}${it.validations?.find((v) => v.linkContentType) ? `(${it.validations.find((v) => v.linkContentType).linkContentType.join('|')})` : ''}>`;
    return `Array<${it.type}>`;
  }
  return f.type;
};
const nodeTypes = {};
const embeddedTypes = {};
function walk(node, ctId) {
  if (!node || typeof node !== 'object') return;
  nodeTypes[node.nodeType] = (nodeTypes[node.nodeType] || 0) + 1;
  if (/embedded-entry|entry-hyperlink/.test(node.nodeType || '')) {
    const id = node.data?.target?.sys?.id;
    const target = ex.entryById.get(id);
    const t = target ? target.sys.contentType.sys.id : '(олдсонгүй)';
    embeddedTypes[`${ctId} → ${node.nodeType} → ${t}`] = (embeddedTypes[`${ctId} → ${node.nodeType} → ${t}`] || 0) + 1;
  }
  if (Array.isArray(node.content)) node.content.forEach((c) => walk(c, ctId));
}

for (const ct of ex.contentTypes.slice().sort((a, b) => a.sys.id.localeCompare(b.sys.id))) {
  const list = byType[ct.sys.id] || [];
  p(`### \`${ct.sys.id}\` (${list.length})`);
  p();
  p('| Талбар | Төрөл | Заавал | mn утгатай | en утгатай | Хязгаарлалт |');
  p('|---|---|---|--:|--:|---|');
  for (const f of ct.fields) {
    if (f.disabled || f.omitted) continue;
    let mn = 0;
    let en = 0;
    for (const e of list) {
      const v = e.fields[f.id];
      if (v?.mn !== undefined && v.mn !== null && v.mn !== '') mn++;
      if (v?.en !== undefined && v.en !== null && v.en !== '') en++;
      if (f.type === 'RichText') for (const loc of Object.keys(v || {})) walk(v[loc], ct.sys.id);
    }
    const vals = [...(f.validations || []), ...(f.items?.validations || [])]
      .map((v) => (v.in ? `in: ${v.in.join(', ')}` : v.unique ? 'unique' : v.size ? `size ${JSON.stringify(v.size)}` : ''))
      .filter(Boolean)
      .join('; ');
    p(`| ${f.id}${f.localized ? ' 🌐' : ''} | ${typeLabel(f)} | ${f.required ? 'тийм' : ''} | ${mn} | ${en} | ${vals.slice(0, 160)} |`);
  }
  p();
}

p('### Rich text node-ууд (бүх entry, бүх locale)');
p();
p('| nodeType | Тоо |');
p('|---|--:|');
for (const [k, v] of Object.entries(nodeTypes).sort((a, b) => b[1] - a[1])) p(`| ${k} | ${v} |`);
p();
p('### Rich text доторх entry холбоос');
p();
p('| Хаанаас → node → ямар төрөл | Тоо |');
p('|---|--:|');
for (const [k, v] of Object.entries(embeddedTypes).sort((a, b) => b[1] - a[1])) p(`| ${k} | ${v} |`);
p();

// --- Asset
const mimes = {};
let bytes = 0;
let withDesc = 0;
let withCredit = 0;
for (const a of ex.assets) {
  const file = a.fields.file?.mn || Object.values(a.fields.file || {})[0];
  if (file) {
    mimes[file.contentType] = (mimes[file.contentType] || 0) + 1;
    bytes += file.details?.size || 0;
  }
  const d = a.fields.description?.mn;
  if (d) withDesc++;
  if (d && /Зураг:/.test(d)) withCredit++;
}
p(`### Asset: ${ex.assets.length}, ${(bytes / 1024 / 1024).toFixed(0)} MB`);
p();
p(`Тайлбартай: ${withDesc}, «Зураг:» кредиттэй: ${withCredit}.`);
p();
p('| MIME | Тоо |');
p('|---|--:|');
for (const [k, v] of Object.entries(mimes).sort((a, b) => b[1] - a[1])) p(`| ${k} | ${v} |`);

process.stdout.write(out.join('\n') + '\n');
